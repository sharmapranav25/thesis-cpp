"""Decoder-only instance-aware renderer; existing controller rendering is untouched.

Geometry is a per-glyph soft coverage map before occlusion. Visible coverage tracks
compositing and resampling, not a claimed physical alpha decomposition after JPEG.
External effects are reused through a scoped warp hook in a single render thread.
"""
import contextlib
import copy
import math
import threading
from pathlib import Path
import numpy as np
from PIL import Image, ImageFont
from scipy import ndimage
from .. import runtime as U
from captcha_effects.canvas import Canvas
from captcha_effects import render as R, text as T, warp as W, extras as X
from captcha_effects.effects import REGISTRY
from captcha_effects.captcha import calibration
from captcha_effects.calibrate import level_of
from captcha_effects.measure import visible_amount

_HOOK_LOCK = threading.Lock()


def box(mask, threshold=.1):
    ys, xs = np.nonzero(mask >= threshold)
    return [int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1] if len(xs) else None


class InstanceCanvas(Canvas):
    def __post_init__(self):
        super().__post_init__()
        self.geometry = {}
        self.visible = {}
        self.decoration = {}
        self.active_parent = None
        self.transforms = []
        self.background_scene = None
        self.background_opaque = None
        self.background_translucent = None

    def blend(self, cov, colour, effect, head, layer, opacity=1., params=None, colour_field=None):
        if self.active_parent is not None and effect in ('shadow','outline','extrude'):
            # Attached decorations are behind all core glyphs, not painted over neighbours.
            core=np.maximum.reduce(list(self.geometry.values()))
            cov=np.asarray(cov).copy();cov[core>=.5]=0
        alpha = np.clip(cov, 0, 1).astype(np.float32) * opacity
        for gid in self.visible:
            self.visible[gid] *= 1 - alpha
        cid = super().blend(cov, colour, effect, head, layer, opacity, params, colour_field)
        if head == 'text':
            self.geometry[cid] = np.clip(cov, 0, 1).astype(np.float32).copy()
            self.visible[cid] = alpha.copy()
            self.decoration[cid] = np.zeros_like(alpha)
        elif self.active_parent is not None:
            gid = self.active_parent
            self.decoration[gid] = np.maximum(self.decoration[gid], alpha)
            self.records[-1]['parent_instance_id'] = gid
        return cid


def nearest_growth(coverage, radius):
    """Nearest source ownership uses sequence positions, never numeric operation IDs."""
    support = np.asarray(coverage) >= .5
    distances = np.stack([ndimage.distance_transform_edt(~m) if m.any()
                          else np.full(m.shape, np.inf) for m in support])
    owner = np.argmin(distances, axis=0)
    return owner, np.min(distances, axis=0) <= radius


def bold(cv, level):
    gids = list(cv.geometry)
    radius = .3 + 2.7 * level / 10
    support = [(cv.opaque == gid) for gid in gids]
    owner, area = nearest_growth(support, radius)
    original = np.any(support, axis=0)
    grown = area & ~original
    for i, gid in enumerate(gids):
        m = grown & (owner == i)
        source = support[i]
        if not source.any():
            continue
        _, indices = ndimage.distance_transform_edt(~source, return_indices=True)
        cv.img[m] = cv.img[indices[0][m], indices[1][m]]
        cv.opaque[m] = gid
        for other in gids:
            cv.visible[other][m] = 0
        cv.visible[gid][m] = 1
        cv.geometry[gid][m] = 1
    measured = float(grown.sum() / max(1, original.sum()))
    cv.record(effect='bold', head='stroke_bold', layer='glyph', params={'width': radius}, measured=measured)
    return dict(width=radius, measured=measured)


@contextlib.contextmanager
def track_warps(cv):
    """Intercept the actual displacement generated by each existing effect."""
    with _HOOK_LOCK:
        original, extra = W._remap, X._remap
        def remap(canvas, dx, dy):
            if canvas is cv:
                yy, xx = np.mgrid[:cv.h, :cv.w].astype(np.float32)
                coords = np.array([np.clip(yy + dy, 0, cv.h - 1), np.clip(xx + dx, 0, cv.w - 1)])
                for maps in [cv.geometry, cv.visible, cv.decoration]:
                    for gid, mask in maps.items():
                        maps[gid] = ndimage.map_coordinates(mask, coords, order=1, mode='nearest')
                if cv.background_scene is not None:
                    cv.background_scene = np.stack([ndimage.map_coordinates(cv.background_scene[..., c], coords,
                                                   order=1, mode='nearest') for c in range(3)], -1)
                cv.transforms.append(dict(kind='displacement', mean_pixels=float(np.mean(np.hypot(dx, dy))),
                                          source='recorded effect seed and pinned renderer source'))
            return original(canvas, dx, dy)
        W._remap = X._remap = remap
        try:
            yield
        finally:
            W._remap, X._remap = original, extra


def glyph(meta, char, pixels, axes, stretch, shear, angle, stroke):
    if char not in meta['chars']:
        raise ValueError('Missing glyph: ' + meta['key'] + '/' + char)
    values = {a['tag']: float(np.clip(axes.get(a['tag'], a['default']), a['min'], a['max'])) for a in meta['axes']}
    font = ImageFont.truetype(meta['path'], max(4, int(pixels * 4)))
    if values:
        # Fail explicitly rather than labelling an axis request that was ignored.
        font.set_variation_by_axes([values[a['tag']] for a in meta['axes']])
    # Reuse supersampled rasterization with an exact, temporary font constructor.
    # This renderer is process-parallel, not thread-parallel.
    original = T._font_with_axes
    T._font_with_axes = lambda *args, **kwargs: font
    try:
        mask = T.glyph_mask(meta, char, pixels, ss=4, stroke=stroke, x_scale=stretch, slant=shear, angle=angle)
    finally:
        T._font_with_axes = original
    if mask is None or not (mask >= .1).any():
        raise ValueError('Empty glyph')
    return mask, values


def draw_instances(cv, spec, fonts, rng):
    chars = spec['text']
    row_count = 2 if spec['layout'] == 'two_layer' else 1
    split = (len(chars) + 1) // 2
    prepared = []
    for i, char in enumerate(chars):
        meta = fonts[spec['font_keys'][i]]
        pixels = spec['size_fraction'] * cv.h * float(rng.uniform(1 - spec['size_jitter'], 1 + spec['size_jitter']))
        angle = float(rng.uniform(-spec['rotation'], spec['rotation']))
        axes = spec['axes'][i]
        mask, actual = glyph(meta, char, pixels, axes, spec['stretch'], spec['shear'], angle, spec['stroke'])
        prepared.append(dict(index=i, char=char, row=int(row_count == 2 and i >= split), font_key=meta['key'],
                             font_sha256=meta['sha256'], family=meta['family'], family_group=meta['family_group'],
                             style=meta['style'], axes=actual, axis_application='success', angle=angle,
                             shear=spec['shear'], stretch=spec['stretch'], size_px=pixels, mask=mask,
                             colour=spec['colours'][i], italic=meta['italic'], category=meta['category'],
                             stroke_class=meta['stroke'], x_height=meta['x_height'], intrinsic_width=meta['width_rel']))
    rows = [[p for p in prepared if p['row'] == r] for r in range(row_count)]
    ref = float(np.median([p['mask'].shape[0] for p in prepared]))
    row_widths = [sum(p['mask'].shape[1] for p in row) + spec['spacing'] * ref * (len(row) - 1) for row in rows]
    scale = min(1., .88 * cv.w / max(row_widths), .85 * cv.h / (ref * row_count * 1.12))
    if scale < 1:
        for p in prepared:
            im = Image.fromarray(p['mask'].astype(np.float32), mode='F')
            p['mask'] = np.asarray(im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.Resampling.BOX)).copy()
            p['size_px'] *= scale
    ref *= scale
    total_height = ref * row_count * 1.12
    y_origin = (cv.h - total_height) * spec['y_position']
    phase = float(rng.uniform(0, 2 * math.pi))
    for r, row in enumerate(rows):
        width = sum(p['mask'].shape[1] for p in row) + spec['spacing'] * ref * (len(row) - 1)
        x = (cv.w - width) * spec['x_position']
        for p in row:
            m = p.pop('mask')
            h, w = m.shape
            curve = spec['curve'] * cv.h * math.sin(2 * math.pi * (x + w / 2) / cv.w + phase)
            jitter = float(rng.uniform(-spec['jitter'], spec['jitter'])) * cv.h
            y = y_origin + r * ref * 1.12 + (ref - h) / 2 + curve + jitter
            # All realized placement and clipping is recorded, including clamp effects.
            xi, yi = int(round(x)), int(round(np.clip(y, 0, max(0, cv.h - h))))
            coverage = np.zeros((cv.h, cv.w), np.float32)
            x0, y0 = max(0, xi), max(0, yi)
            x1, y1 = min(cv.w, xi + w), min(cv.h, yi + h)
            if x1 > x0 and y1 > y0:
                coverage[y0:y1, x0:x1] = m[y0-yi:y1-yi, x0-xi:x1-xi]
            p.update(position=[xi, yi], clipped_fraction=float(1 - coverage.sum() / max(1e-6, m.sum())),
                     fit_scale=scale, stroke_width=T.stroke_width_px(m))
            p['id'] = cv.blend(coverage, p['colour'], 'text', 'text', 'text', params=copy.deepcopy(p))
            x += w + spec['spacing'] * ref
    return prepared


def apply_glyph(cv, item, rng):
    name, level = item['name'], item['level']
    if name == 'bold':
        return bold(cv, level)
    values = []
    for gid in cv.geometry:
        cv.active_parent = gid
        before = (cv.opaque == gid)
        before_rgb=cv.img.copy() if name in ('hollow','thin','translucent') else None
        result = REGISTRY[name]['fn'](cv, level, rng, ids=[gid], **item.get('style', {}))
        after = cv.opaque == gid
        if name == 'thin':
            removed = before & ~after
            cv.geometry[gid][removed] = 0
            cv.img[removed]=cv.background_scene[removed]
            cv.opaque[removed]=cv.background_opaque[removed]
            cv.translucent[removed]=cv.background_translucent[removed]
            for other in cv.visible:
                cv.visible[other][removed]=0
        elif name == 'hollow':
            # Clear the same one-pixel-eroded interior as the underlying operation.
            from captcha_effects.glyph import _morph
            inner = _morph(before, 1, False) & before
            cv.img[inner]=before_rgb[inner]*(1-result['clear'])+cv.background_scene[inner]*result['clear']
            cv.geometry[gid][inner] *= 1 - result['clear']
            for other in cv.visible:
                cv.visible[other][inner] *= 1-result['clear']
            if result['clear']>=.5:
                cv.opaque[inner]=cv.background_opaque[inner]
                cv.translucent[inner]=cv.background_translucent[inner]
        elif name == 'translucent':
            cv.img[before]=before_rgb[before]*result['alpha']+cv.background_scene[before]*(1-result['alpha'])
            for other in cv.visible:
                cv.visible[other][before] *= result['alpha']
        values.append(result)
    cv.active_parent = None
    return dict(measured=float(np.mean([p.get('measured', 0) for p in values])), instances=values)


def resample_coverage(cv, name, params):
    if name not in ('pixelate', 'resample', 'blur'):
        return
    from PIL import ImageFilter
    for gid in cv.visible:
        # Visible support is degraded; underlying geometric extent remains separate.
        im = Image.fromarray(np.clip(cv.visible[gid] * 255, 0, 255).astype(np.uint8))
        if name == 'blur':
            im = im.filter(ImageFilter.GaussianBlur(params['sigma']))
        elif name == 'pixelate':
            b = params['block']
            im = im.resize((max(1, int(cv.w/b)), max(1, int(cv.h/b))), Image.Resampling.BILINEAR).resize((cv.w,cv.h), Image.Resampling.NEAREST)
        else:
            f = params['factor']
            im = im.resize((max(2, int(cv.w/f)), max(2, int(cv.h/f))), getattr(Image.Resampling, params['down'])).resize((cv.w,cv.h), Image.Resampling.BICUBIC)
        cv.visible[gid] = np.asarray(im, np.float32) / 255


def render(recipe, fonts):
    rng = np.random.default_rng(recipe['render_seed'])
    w, h = recipe['size']
    cv = InstanceCanvas(w, h, tuple(recipe['background']))
    effects = recipe['effects']
    logs = []
    font_paths = sorted({fonts[k]['path'] for k in recipe['text']['font_keys']})
    def stage(names, text_box=None):
        for item in effects:
            if item['name'] not in names:
                continue
            name = item['name']
            if name in R.GLYPH_EFFECTS:
                p = apply_glyph(cv, item, rng)
            else:
                p = REGISTRY[name]['fn'](cv, item['level'], rng, text_box=text_box, font_paths=font_paths, **item.get('style', {}))
                if cv.records and cv.records[-1].get('effect') == name:
                    p = {**cv.records[-1].get('params', {}), **p}
                resample_coverage(cv, name, p)
            logs.append(dict(name=name, head=REGISTRY[name]['head'], level_requested=item['level'], params=p))
    with track_warps(cv):
        stage(R.UNDER)
        cv.background_scene = cv.img.copy()
        cv.background_opaque=cv.opaque.copy()
        cv.background_translucent=cv.translucent.copy()
        glyphs = draw_instances(cv, recipe['text'], fonts, np.random.default_rng([recipe['render_seed'], 1]))
        cv.text_colour = tuple(glyphs[0]['colour'])
        stage(R.GLYPH_EFFECTS)
        union = np.maximum.reduce(list(cv.geometry.values()))
        stage(R.OVER, box(union))
        stage(R.POST)
    labels = {}
    cal = calibration()
    for log in logs:
        value = visible_amount(log['name'], cv.records, cv.opaque, cv.translucent, cv.background, log['params'].get('measured'))
        level = level_of(cal, log['name'], value)
        old = labels.get(log['head'])
        if old is None or level > old['level']:
            labels[log['head']] = dict(present=int(level > 0), level=level, measured=value,
                                       requested=log['level_requested'], effect=log['name'])
    for name in R.SAMPLED:
        labels.setdefault(REGISTRY[name]['head'], dict(present=0, level=0, measured=0., effect=None))
    image = cv.image()
    # These exact coverage values are exported losslessly as uint8 masks.
    # Quantize before deriving boxes so reloaded annotations use identical support.
    for maps in (cv.geometry, cv.visible, cv.decoration):
        for gid in maps:
            maps[gid] = np.rint(np.clip(maps[gid], 0, 1)*255).astype(np.float32)/255
    luminance = image @ np.array([.299,.587,.114])
    for g in glyphs:
        gid = g['id']
        g.update(box_core=box(cv.geometry[gid]), box_visible=box(cv.visible[gid]),
                 box_decorated=box(np.maximum(cv.geometry[gid], cv.decoration[gid])),
                 visible_fraction=float(np.clip(cv.visible[gid].sum() / max(1e-6, cv.geometry[gid].sum()), 0, 1)))
        mask = cv.visible[gid] >= .2
        g['final_colour_median'] = np.median(image[mask], axis=0).tolist() if mask.any() else None
        ring = ndimage.binary_dilation(mask,iterations=3) & ~mask
        g['local_contrast'] = abs(float(np.median(luminance[mask])-np.median(luminance[ring]))) if mask.any() and ring.any() else 0.
        core = cv.geometry[gid] >= .1
        g['touches_canvas_edge'] = bool(core[0].any() or core[-1].any() or core[:,0].any() or core[:,-1].any())
        g['visible_pixels'] = int(mask.sum())
    valid = (len(glyphs) == len(recipe['text']['text']) and all(g['box_core'] and g['box_visible']
             and g['clipped_fraction'] <= .05 and g['visible_fraction'] >= .25 and not g['touches_canvas_edge']
             and g['visible_pixels'] >= 10 and g['box_core'][3]-g['box_core'][1] >= 7 and g['local_contrast'] >= 12 for g in glyphs))
    quality=dict(min_visibility=min(g['visible_fraction'] for g in glyphs),min_contrast=min(g['local_contrast'] for g in glyphs),
                 min_height=min(g['box_core'][3]-g['box_core'][1] if g['box_core'] else 0 for g in glyphs))
    quality['difficulty']='hard' if quality['min_visibility']<.6 or quality['min_contrast']<40 or quality['min_height']<12 or len(effects)>=4 else 'medium' if effects else 'easy'
    return dict(image=image, glyphs=glyphs, geometry=np.stack(list(cv.geometry.values())),
                visible=np.stack(list(cv.visible.values())), decoration=np.stack(list(cv.decoration.values())),
                background_scene=np.clip(cv.background_scene,0,255).astype(np.uint8), effects=labels,
                effect_log=logs, records=cv.records, transforms=cv.transforms, valid=bool(valid),
                count=len(glyphs), rows=len({g['row'] for g in glyphs}),quality=quality,
                schema='capri-decoder-instances-v1', boxes='xyxy exclusive; soft-mask threshold .1')
